// Concatenates the render-blocking stylesheets into one file.
//
// The site shipped nine of them, each a separate render-blocking request. On
// the throttled profile that is nine round-trips at 150ms RTT before anything
// can paint, and nine parses. Nothing about the CSS needs to be in nine files
// at request time -- that split is for people reading the source, and it is
// kept there.
//
// This does not rewrite a single rule. Order is the whole contract: bridge.css
// has to come after the legacy sheets because those carry their own
// !important and a later sheet wins at equal specificity. Concatenating in the
// documented order preserves the cascade exactly; reordering silently breaks
// roughly forty overrides per page, which is how that bug arrived the first
// time.
//
//   node tools/bundle-css.mjs           write it
//   node tools/bundle-css.mjs --check   fail if stale (CI / npm run verify)

import fs from 'node:fs';
import path from 'node:path';

const REPO = path.resolve(import.meta.dirname, '..');
const OUT = path.join(REPO, 'public/assets/css/site.css');

// The order the layout used to link them in. Do not sort this.
const ORDER = [
  'public/assets/theme/engine.css',   // tokens first: everything below reads them
  'public/assets/css/base.css',       // legacy monolith
  'public/assets/css/components.css',
  'public/assets/css/sections.css',
  'public/assets/css/trust.css',
  'public/assets/theme/bridge.css',   // MUST follow the legacy four
  'public/assets/theme/glass.css',
  'public/assets/theme/motion.css',
  'public/assets/theme/panel.css'
];

const parts = [
  '/* GENERATED by tools/bundle-css.mjs — do not edit.\n' +
  '   Sources are the files listed below, concatenated in cascade order.\n' +
  '   Edit those; run `npm run css` to regenerate. */\n'
];

for (const rel of ORDER) {
  const p = path.join(REPO, rel);
  if (!fs.existsSync(p)) {
    console.error(`missing source: ${rel}`);
    process.exit(1);
  }
  parts.push(`\n/* ══════════ ${rel} ══════════ */\n`);
  parts.push(fs.readFileSync(p, 'utf8').trimEnd());
  parts.push('\n');
}

const next = parts.join('');
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';

if (process.argv.includes('--check')) {
  if (next !== prev) {
    console.error('public/assets/css/site.css is out of date — run: npm run css');
    process.exit(1);
  }
  console.log('site.css is current');
} else {
  fs.writeFileSync(OUT, next);
  const kb = (n) => Math.round(n / 1024);
  console.log(`site.css: ${kb(next.length)} kB from ${ORDER.length} sources ` +
              `(was ${ORDER.length} render-blocking requests, now 1)`);
}
