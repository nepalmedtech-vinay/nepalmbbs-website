/* NepalMBBS.in — actions.js
   One delegated listener in place of 117 inline on* attributes.

   This exists so the site can send a Content-Security-Policy without
   'unsafe-inline' on script-src. That header is what decides whether an HTML
   injection is a scripting bug or a formatting bug, and a single inline
   onclick= anywhere in the markup forces 'unsafe-inline' back on for the whole
   document, which switches the protection off.

   Markup carries the intent as data rather than as code:

     <button data-act="click" data-do='[["selectCollege","@el","all"]]'>

   Names are resolved through the allow-list below, not by indexing window with
   whatever the attribute says. Under CSP the remaining lever an attacker has is
   injected *markup*, so a dispatcher that will call any global by name would
   hand back most of what the CSP just took away. The list is generated by
   tools/dehandler.py from the handlers actually present, and
   tests/build-verify.mjs fails if the built HTML references a name outside it.

   Behaviour is deliberately identical to the inline handlers it replaces:
   nothing calls preventDefault, so a button inside a form still submits and an
   anchor still follows its href, exactly as before. */

(function () {
  'use strict';

  var ALLOW = {
    addCollegeAdmin: 1,
    // Live content, added with the runtime CMS. Two allow-lists exist and
    // both have to know a name: this one, which the dispatcher actually
    // checks at runtime, and tools/action-allowlist.json, which
    // compare-verify checks the markup against. Adding a name to only the
    // JSON passes that test and silently does nothing in the browser —
    // csp-verify is what catches it, reporting `want [["addCollegeMedia"]]
    // got []`.
    addCollegeMedia: 1,
    addCollegeNotice: 1,
    deleteCollegeMedia: 1,
    deleteCollegeNotice: 1,
    loadCollegeMedia: 1,
    loadCollegeNotices: 1,
    addFAQ: 1,
    addTestimonial: 1,
    addTicker: 1,
    addVideo: 1,
    askBot: 1,
    changePass: 1,
    checkEligibility: 1,
    closeAdmin: 1,
    closeChat: 1,
    closeMenu: 1,
    closeModal: 1,
    convertCurr: 1,
    deleteCollege: 1,
    deleteFAQ: 1,
    deleteTest: 1,
    deleteVideo: 1,
    doAdminLogin: 1,
    doAdminReset: 1,
    enquireCollege: 1,
    exportCSV: 1,
    loadAdminColleges: 1,
    loadDashboard: 1,
    loadLeadsTable: 1,
    openAdmin: 1,
    playVid: 1,
    removeNMCVid: 1,
    restartChat: 1,
    saveCalendly: 1,
    saveGA: 1,
    saveHeroH1: 1,
    saveNMCVid: 1,
    savePhone: 1,
    saveSet: 1,
    saveWANum: 1,
    selectCollege: 1,
    sendMsg: 1,
    setLang: 1,
    submitLead: 1,
    switchATab: 1,
    switchGuide: 1,
    switchTab: 1,
    testWACall: 1,
    toggleChat: 1,
    toggleFaq: 1,
    toggleFeature: 1,
    toggleMenu: 1,
    updateCities: 1,
    updateLeadStage: 1
  };

  function run(el) {
    var spec;
    try { spec = JSON.parse(el.getAttribute('data-do') || '[]'); }
    catch (e) { return; }
    if (!Array.isArray(spec)) return;

    for (var i = 0; i < spec.length; i++) {
      var call = spec[i];
      if (!Array.isArray(call) || !call.length) continue;
      var name = call[0];

      // hasOwnProperty, not `in`: `constructor` and `toString` are on every
      // object, and `ALLOW[name]` alone would happily resolve them.
      if (typeof name !== 'string' ||
          !Object.prototype.hasOwnProperty.call(ALLOW, name)) continue;

      var fn = window[name];
      if (typeof fn !== 'function') continue;

      var args = [];
      for (var j = 1; j < call.length; j++) {
        args.push(call[j] === '@el' ? el : call[j]);
      }

      // One failing action must not stop the others on the same element, and
      // must not take the page down with it.
      try { fn.apply(null, args); }
      catch (e) { if (window.console) console.error('action ' + name + ':', e); }
    }
  }

  function on(type, act) {
    document.addEventListener(type, function (e) {
      var t = e.target;
      if (!t || t.nodeType !== 1) return;
      // closest(), because a click usually lands on an icon or a span inside
      // the button that carries the attribute.
      var el = t.closest('[data-act="' + act + '"]');
      if (el) run(el);
    });
  }

  /* Build the pair of attributes from JS that generates markup. Callers used
     to concatenate a value straight into onclick="fn('" + id + "')", which
     breaks -- or injects -- the moment the value contains a quote. JSON plus
     entity-escaping removes that whole class of bug. */
  window.actAttr = function (event, calls) {
    return 'data-act="' + event + '" data-do="' +
      JSON.stringify(calls)
        .replace(/&/g, '&amp;').replace(/"/g, '&quot;')
        .replace(/</g, '&lt;').replace(/>/g, '&gt;') + '"';
  };

  on('click', 'click');
  on('change', 'change');
  on('input', 'input');

  // The originals were onkeypress="if(event.key==='Enter')fn()". keypress is
  // deprecated; keydown fires for Enter in every browser that matters and is
  // what the deprecation notice points at.
  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Enter') return;
    var t = e.target;
    if (!t || t.nodeType !== 1) return;
    var el = t.closest('[data-act="enter"]');
    if (el) run(el);
  });
})();
